def set_language(language: str):
    global _LANGUAGE
    _LANGUAGE = "en" if language == "en" else "fa"


def current_language() -> str:
    return _LANGUAGE


def is_rtl() -> bool:
    return _LANGUAGE != "en"


def direction():
    return Qt.LayoutDirection.RightToLeft if is_rtl() else Qt.LayoutDirection.LeftToRight


def align_start():
    if is_rtl():
        return Qt.AlignmentFlag.AlignRight | Qt.AlignmentFlag.AlignVCenter | Qt.AlignmentFlag.AlignAbsolute
    return Qt.AlignmentFlag.AlignLeft | Qt.AlignmentFlag.AlignVCenter | Qt.AlignmentFlag.AlignAbsolute


def t(key: str, **kwargs):
    catalog = _STRINGS["en"] if _LANGUAGE == "en" else _FA
    value = catalog.get(key)
    if value is None:
        value = _FA.get(key, key)
    if isinstance(value, str) and kwargs:
        try:
            return value.format(**kwargs)
        except Exception:
            return value
    return value


def field_types() -> dict:
    keys = [
        "short_text", "long_text", "rich_text", "html", "number", "decimal",
        "file", "image", "pdf", "radio", "select", "checkbox", "date", "time", "datetime",
    ]
    return {key: t(f"types.{key}") for key in keys}
